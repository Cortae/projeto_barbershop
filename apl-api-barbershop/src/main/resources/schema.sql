-- ------------------------------------------------------------
-- Tabelas
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS tipo_usuario (
                                            id_tipo_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            titulo VARCHAR(45) NOT NULL UNIQUE
    );

CREATE TABLE IF NOT EXISTS usuario (
                                       id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       nome VARCHAR(60),
    email VARCHAR(60) NOT NULL UNIQUE,
    celular VARCHAR(11) UNIQUE,
    fk_tipo_usuario INT NOT NULL,
    senha VARCHAR(255),
    CONSTRAINT fk_usuario_tipo_usuario
    FOREIGN KEY (fk_tipo_usuario) REFERENCES tipo_usuario(id_tipo_usuario)
    );

CREATE TABLE IF NOT EXISTS status_agendamento (
                                                  id_status_agendamento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  titulo VARCHAR(30) NOT NULL UNIQUE
    );

CREATE TABLE IF NOT EXISTS cliente (
                                       id_cliente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       nome VARCHAR(60) NOT NULL,
    apelido VARCHAR(45),
    celular VARCHAR(11),
    nascimento DATE
    );

CREATE TABLE IF NOT EXISTS forma_pagamento (
                                               id_forma_pagamento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               titulo VARCHAR(45) NOT NULL UNIQUE
    );

CREATE TABLE IF NOT EXISTS pagamento (
                                         id_pagamento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         valor DECIMAL(10,2) NOT NULL,
    pago BOOLEAN NOT NULL,
    data_pagamento TIMESTAMP,
    fk_forma_pagamento INT,
    CONSTRAINT fk_pagamento_forma_pagamento
    FOREIGN KEY (fk_forma_pagamento) REFERENCES forma_pagamento(id_forma_pagamento)
    );

CREATE TABLE IF NOT EXISTS agendamento (
                                           id_agendamento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           horario_inicio TIMESTAMP NOT NULL,
                                           horario_fim TIMESTAMP NOT NULL,
                                           titulo VARCHAR(80),
    fk_status_agendamento INT NOT NULL,
    barbeiro INT NOT NULL,
    fk_cliente INT NOT NULL,
    fk_pagamento INT NOT NULL,
    CONSTRAINT fk_agendamento_status
    FOREIGN KEY (fk_status_agendamento) REFERENCES status_agendamento(id_status_agendamento),
    CONSTRAINT fk_agendamento_usuario
    FOREIGN KEY (barbeiro) REFERENCES usuario(id_usuario),
    CONSTRAINT fk_agendamento_cliente
    FOREIGN KEY (fk_cliente) REFERENCES cliente(id_cliente),
    CONSTRAINT fk_agendamento_pagamento
    FOREIGN KEY (fk_pagamento) REFERENCES pagamento(id_pagamento)
    );

CREATE TABLE IF NOT EXISTS servico (
                                       id_servico INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       titulo VARCHAR(45) NOT NULL,
    valor_atual DECIMAL(10,2) NOT NULL,
    duracao_atual INT NOT NULL,
    ativo BOOLEAN NOT NULL
    );

CREATE TABLE IF NOT EXISTS agendamento_servico(
                                                    id_agendamento_servico INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                    fk_agendamento INT NOT NULL,
                                                    fk_servico INT NOT NULL,
                                                    valor_unitario DECIMAL(10,2) NOT NULL,
    duracao INT NOT NULL,
    CONSTRAINT uq_agendamento_servico UNIQUE (fk_agendamento, fk_servico),
    CONSTRAINT fk_agendamento_servico_agendamento
    FOREIGN KEY (fk_agendamento) REFERENCES agendamento(id_agendamento),
    CONSTRAINT fk_agendamento_servico_servico
    FOREIGN KEY (fk_servico) REFERENCES servico(id_servico)
    );

CREATE TABLE IF NOT EXISTS api_request_log (
                                               id_api_request_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               request_id CHAR(36) NOT NULL UNIQUE,
                                               started_at TIMESTAMP(3) NOT NULL,
                                               finished_at TIMESTAMP(3) NOT NULL,
                                               duration_ms BIGINT NOT NULL,
                                               event_type VARCHAR(30) NOT NULL,
                                               http_method VARCHAR(10) NOT NULL,
                                               endpoint VARCHAR(500) NOT NULL,
                                               query_params JSON,
                                               request_headers JSON,
                                               request_body JSON,
                                               request_body_bytes BIGINT NOT NULL DEFAULT 0,
                                               request_body_truncated BOOLEAN NOT NULL DEFAULT FALSE,
                                               response_status SMALLINT NOT NULL,
                                               response_headers JSON,
                                               response_body JSON,
                                               response_body_bytes BIGINT NOT NULL DEFAULT 0,
                                               response_body_truncated BOOLEAN NOT NULL DEFAULT FALSE,
                                               source_ip VARCHAR(45),
                                               user_agent VARCHAR(500),
                                               fk_usuario INT,
                                               error_code VARCHAR(50),
    CONSTRAINT fk_api_request_log_usuario
    FOREIGN KEY (fk_usuario) REFERENCES usuario(id_usuario)
    ON DELETE SET NULL
    );

CREATE INDEX IF NOT EXISTS idx_api_request_log_started_at
    ON api_request_log(started_at);
CREATE INDEX IF NOT EXISTS idx_api_request_log_status
    ON api_request_log(response_status);
CREATE INDEX IF NOT EXISTS idx_api_request_log_event_type
    ON api_request_log(event_type);
CREATE INDEX IF NOT EXISTS idx_api_request_log_usuario_started_at
    ON api_request_log(fk_usuario, started_at);

CREATE TABLE IF NOT EXISTS expediente (
                                          id_expediente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          dia_semana TINYINT NOT NULL,
                                          fk_usuario INT NOT NULL,
                                          aberto BOOLEAN,
                                          hora_abertura TIME,
                                          hora_fechamento TIME,
                                          intervalo_inicio TIME,
                                          intervalo_fim TIME,
                                          CONSTRAINT unq_usuario_dia UNIQUE (fk_usuario, dia_semana),
    CONSTRAINT fk_expediente_usuario
    FOREIGN KEY (fk_usuario) REFERENCES usuario(id_usuario)
    );

CREATE TABLE IF NOT EXISTS bloqueio (
                                        id_bloqueio INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        fk_usuario INT NOT NULL,
                                        inicio TIMESTAMP NOT NULL,
                                        fim TIMESTAMP NOT NULL,
                                        motivo VARCHAR(100),
    CONSTRAINT fk_bloqueio_usuario
    FOREIGN KEY (fk_usuario) REFERENCES usuario(id_usuario)
    );

CREATE TABLE IF NOT EXISTS despesa (
                                       id_despesa INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       fk_usuario INT NOT NULL,
                                       descricao VARCHAR(100) NOT NULL,
    valor DECIMAL(10,2) NOT NULL,
    data_despesa DATE NOT NULL,
    CONSTRAINT fk_despesa_usuario
    FOREIGN KEY (fk_usuario) REFERENCES usuario(id_usuario)
    );
